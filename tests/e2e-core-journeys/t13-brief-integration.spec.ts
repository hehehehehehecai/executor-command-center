import { expect, test, request } from "@playwright/test";
import { spawnSync } from "node:child_process";
import { verifiedContainerName } from "../../scripts/isolated-test-target.mjs";
import { cleanupPhase5Identity, prepareCompletedSync, seedPhase5Identity, type Phase5Identity } from "./phase5-fixture";

function fixtureSql(sql: string): string {
  const result = spawnSync("docker", ["exec", verifiedContainerName(), "psql", "-U", "postgres", "-d", "postgres", "-v", "ON_ERROR_STOP=1", "-t", "-A", "-c", sql], { encoding: "utf8", windowsHide: true });
  expect(result.status, result.stderr).toBe(0);
  return result.stdout.trim();
}

test("T13 本人持久活动生成正文与来源，响应丢失刷新恢复原key且仅收费一次", async ({ page }, testInfo) => {
  let actor: Phase5Identity | undefined;
  let other: Phase5Identity | undefined;
  const sourceId = "a".repeat(40);
  const sourceRowId = crypto.randomUUID();
  const observedBodies: { rangeStart: string; rangeEnd: string; requestKey: string }[] = [];
  const providerBefore = await (await page.request.get("http://127.0.0.1:4015/__fixture/state")).json();
  const initialModelCalls = providerBefore.calls.filter((call: { pathname: string }) => call.pathname === "/chat/completions").length;
  await testInfo.attach("t11-before-creation-contract", { body: JSON.stringify({ at: new Date().toISOString(), caseId: "T13-BRIEF", batch: process.env.EXECUTOR_TEST_EXECUTION_BATCH_ID, subjectIntents: [17, 18], sourceId, sourceRowId, source: "本地合成，两次SDK真实返回UUID由既有observer在业务写入前绑定" }), contentType: "application/json" });
  try {
    actor = await seedPhase5Identity(17);
    other = await seedPhase5Identity(18);
    await testInfo.attach("t11-registered-subjects", { body: JSON.stringify({ at: new Date().toISOString(), actors: [actor, other].map(x => ({ userId: x.userId, projectId: x.projectId, installationId: x.installationId, selectedRepositoryId: x.selectedRepositoryId })), sourceRowId, sourceId }), contentType: "application/json" });
    const occurredAt = new Date().toISOString();
    expect([sourceRowId, actor.projectId, actor.userId].every(id => /^[0-9a-f-]{36}$/.test(id))).toBe(true);
    const seeded = fixtureSql(`insert into public.github_commits(id,project_id,github_object_id,message,committed_at,source_updated_at,source_version) select '${sourceRowId}'::uuid, id, '${sourceId}', 'T11 持久提交：完成本人项目入口', '${occurredAt}'::timestamptz, '${occurredAt}'::timestamptz, 't11-local-v1' from public.projects where id='${actor.projectId}'::uuid and user_id='${actor.userId}'::uuid returning id;`);
    expect(seeded).toContain(sourceRowId);
    await prepareCompletedSync(actor);
    await page.goto("/");
    const login = await page.request.post("/api/testing/phase5/session", { headers: { origin: "http://127.0.0.1:3015", "x-phase5-e2e-control-token": process.env.PHASE5_E2E_CONTROL_TOKEN! }, data: { email: actor.email, password: actor.password } });
    expect(login.status()).toBe(200);
    await login.body();
    await page.goto(`/copilot?projectId=${actor.projectId}`);
    const selector = page.getByRole("combobox", { name: "选择项目" });
    await expect(selector).toBeVisible();
    await expect(selector.locator("option")).toHaveCount(1);
    const names = await selector.locator("option").allTextContents();
    expect(names).toHaveLength(1);
    expect(names[0]).not.toBe(actor.projectId);
    await selector.selectOption({ label: names[0] });
    await page.getByRole("button", { name: "切换项目" }).click();
    await expect(page.getByText("当前项目暂无已完成简报。")).toBeVisible();
    await page.route(`**/api/projects/${actor.projectId}/briefs/generate`, async route => {
      observedBodies.push(route.request().postDataJSON());
      const response = await route.fetch();
      expect(response.status()).toBe(200);
      await response.body();
      await route.abort("failed");
    });
    await page.getByRole("button", { name: "生成项目简报" }).click();
    await expect(page.getByRole("region", { name: "生成项目简报" }).getByRole("alert")).toContainText("本次结果尚未确认");
    expect(observedBodies).toHaveLength(1);
    const original = observedBodies[0];
    await page.unroute(`**/api/projects/${actor.projectId}/briefs/generate`);
    await page.reload();
    await expect(page.getByRole("region", { name: "项目简报", exact: true })).toBeVisible();
    await expect(page.getByText(/生成于/)).toBeVisible();
    await expect(page.getByText(/已恢复本次生成请求/)).toBeVisible();
    const restored = await page.evaluate(id => JSON.parse(sessionStorage.getItem(`project-brief-intent:${id}`)!), actor.projectId);
    expect({ rangeStart: restored.rangeStart, rangeEnd: restored.rangeEnd, requestKey: restored.requestKey }).toEqual(original);
    await page.getByRole("button", { name: "生成项目简报" }).click();
    await expect(page.getByText(/本次范围已有已验证简报/)).toBeVisible();
    const repeat = await page.request.post(`/api/projects/${actor.projectId}/briefs/generate`, { headers: { origin: "http://127.0.0.1:3015" }, data: original });
    expect(repeat.status()).toBe(200);
    const replay = await repeat.json();
    expect(replay.status).toBe("cache_hit"); expect(replay.energyCharged).toBe(0);
    await page.goto(`/copilot?projectId=${actor.projectId}&briefId=${replay.briefId}`);
    await expect(page.getByRole("region", { name: "项目简报", exact: true })).toBeVisible();
    await page.getByRole("region", { name: "来源与更新时间", exact: true }).getByRole("link").filter({ hasText: "T11 持久提交：完成本人项目入口" }).click();
    const detail = page.getByRole("complementary", { name: "来源详情" });
    await expect(detail).toContainText("T11 持久提交：完成本人项目入口");
    await expect(detail).toContainText("发生时间");
    await expect(detail.getByRole("link", { name: "查看原始来源" })).toHaveAttribute("href", `https://github.com/${actor.repositoryFullName}/commit/${sourceId}`);
    const invalidEvidence = encodeURIComponent(JSON.stringify(["github_commit", "b".repeat(40), actor.projectId]));
    await page.goto(`/copilot?projectId=${actor.projectId}&briefId=${replay.briefId}&selectedEvidence=${invalidEvidence}`);
    await expect(page.getByRole("complementary", { name: "来源详情" })).toHaveCount(0);
    const crossProjectEvidence = encodeURIComponent(JSON.stringify(["github_commit", sourceId, other.projectId]));
    await page.goto(`/copilot?projectId=${actor.projectId}&briefId=${replay.briefId}&selectedEvidence=${crossProjectEvidence}`);
    await expect(page.getByRole("complementary", { name: "来源详情" })).toHaveCount(0);
    const foreign = await page.request.post(`/api/projects/${other.projectId}/briefs/generate`, { headers: { origin: "http://127.0.0.1:3015" }, data: original });
    expect(foreign.status()).toBe(403);
    const crossOrigin = await page.request.post(`/api/projects/${actor.projectId}/briefs/generate`, { headers: { origin: "https://foreign.example.invalid" }, data: original });
    expect(crossOrigin.status()).toBe(403);
    const anonymous = await request.newContext({ baseURL: "http://127.0.0.1:3015" });
    const anonResponse = await anonymous.post(`/api/projects/${actor.projectId}/briefs/generate`, { headers: { origin: "http://127.0.0.1:3015" }, data: original });
    expect(anonResponse.status()).toBe(401); await anonResponse.body(); await anonymous.dispose();
    expect(repeat.headers()["cache-control"]).toContain("private"); expect(repeat.headers()["cache-control"]).toContain("no-store");
    const persisted = JSON.parse(fixtureSql(`select json_build_object('briefs', (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (select id,status,completed_at,range_start,range_end from public.project_briefs where user_id='${actor.userId}'::uuid) x), 'reservations', (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (select request_key,status,amount from public.energy_reservations where user_id='${actor.userId}'::uuid) x), 'ledger', (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (select delta,entry_type from public.energy_ledger_entries where user_id='${actor.userId}'::uuid) x));`)) as { briefs: { id: string; status: string }[]; reservations: { request_key: string; status: string; amount: number }[]; ledger: { delta: number; entry_type: string }[] };
    const briefs = { data: persisted.briefs };
    const reservations = { data: persisted.reservations };
    const ledger = { data: persisted.ledger };
    expect(briefs.data).toHaveLength(1); expect(briefs.data?.[0]).toMatchObject({ id: replay.briefId, status: "completed" });
    expect(reservations.data).toEqual([{ request_key: original.requestKey, status: "consumed", amount: 3 }]);
    expect(ledger.data?.filter(row => row.delta < 0).map(row => row.delta)).toEqual([-3]);
    const provider = await page.request.get("http://127.0.0.1:4015/__fixture/state");
    const providerState = await provider.json();
    const modelCallsDelta = providerState.calls.filter((call: { pathname: string }) => call.pathname === "/chat/completions").length - initialModelCalls;
    expect(modelCallsDelta).toBe(1);
    await testInfo.attach("t11-durable-result-and-safety", { body: JSON.stringify({ actorUserId: actor.userId, otherUserId: other.userId, original, briefs: briefs.data, reservations: reservations.data, ledger: ledger.data, providerCalls: providerState.calls, providerCallsBefore: providerBefore.calls, modelCallsDelta, whitelistSource: sourceId, foreignStatus: foreign.status(), crossOriginStatus: crossOrigin.status(), anonymousStatus: anonResponse.status() }), contentType: "application/json" });
    const changed = fixtureSql(`update public.github_commits set message='T11 证据已变更', source_version='t11-local-v2' where id='${sourceRowId}'::uuid and project_id='${actor.projectId}'::uuid returning id;`);
    expect(changed).toContain(sourceRowId);
    await page.goto(`/copilot?projectId=${actor.projectId}&briefId=${replay.briefId}`);
    await expect(page.getByText("简报证据重新验证失败。")).toBeVisible();
    await expect(page.getByRole("region", { name: "项目简报", exact: true })).toHaveCount(0);
  } finally {
    await cleanupPhase5Identity(other); await cleanupPhase5Identity(actor);
    await testInfo.attach("t11-cleanup-complete", { body: JSON.stringify({ at: new Date().toISOString(), subjects: [actor, other].filter(Boolean).map(x => x!.userId), cleanupMethod: "原账号删除流程，完成审计回执按原合同保留" }), contentType: "application/json" });
  }
});
